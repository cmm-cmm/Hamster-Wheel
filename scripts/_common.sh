#!/usr/bin/env bash
# Shared helpers for the development scripts. Sourced, never executed.

repo_root() {
    cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd
}

# Prints an absolute path to a PHP CLI binary, or nothing when none is found.
# Resolution order matches tests/php_worker.rs: HAMSTER_PHP, the vendored
# Windows runtime, then PATH.
hamster_php() {
    local root="$1"
    if [ -n "${HAMSTER_PHP:-}" ] && [ -f "${HAMSTER_PHP}" ]; then
        printf '%s\n' "${HAMSTER_PHP}"
        return 0
    fi
    if [ -f "${root}/php/8.5/php.exe" ]; then
        printf '%s\n' "${root}/php/8.5/php.exe"
        return 0
    fi
    command -v php 2>/dev/null || true
}

# Writes a development configuration to stdout. The PHP location is emitted
# only when a PHP CLI exists, because the server rejects a configuration whose
# executable cannot be resolved.
hamster_dev_config() {
    local root="$1" listen="$2" php="$3"
    printf '# Generated by scripts/. Edit the generator, not this file.\n'
    printf '[server]\nlisten = "%s"\n\n' "${listen}"
    printf '[[hosts]]\nname = "localhost"\naliases = ["127.0.0.1"]\n\n'
    printf '[[hosts.locations]]\npath = "/api"\nhandler = "not_found"\n\n'
    if [ -n "${php}" ]; then
        printf '[[hosts.locations]]\npath = "/php"\nhandler = "php_worker"\n\n'
        printf '[hosts.locations.php]\nexecutable = %s\nscript = %s\n\n' \
            "$(toml_literal "${php}")" \
            "$(toml_literal "${root}/fixtures/php-worker/worker.php")"
    fi
    printf '[[hosts.locations]]\npath = "/"\nhandler = "static"\nroot = %s\n' \
        "$(toml_literal "${root}/public")"
}

toml_literal() {
    printf "'%s'" "${1//\'/\'\'}"
}

# Blocks until the server answers on the given address, or fails after ~10s.
wait_for_http() {
    local url="$1" attempt
    for attempt in $(seq 1 100); do
        if curl --fail --silent --output /dev/null "${url}"; then
            return 0
        fi
        sleep 0.1
    done
    printf 'timed out waiting for %s\n' "${url}" >&2
    return 1
}
