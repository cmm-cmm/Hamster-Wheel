use std::{env, fs, path::PathBuf, process::Command};

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=icon/icons/hamster-wheel.ico");
    // A new commit changes the stamp below, so the build must not be cached
    // across one. HEAD moves on every commit, checkout and rebase.
    println!("cargo:rerun-if-changed=.git/HEAD");

    let build = build_stamp();
    println!("cargo:rustc-env=HAMSTER_BUILD_STAMP={build}");

    if env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("windows") {
        // Only the shipped executable gets the icon and the version
        // information, not libraries/benches. Fail instead of silently
        // producing a Windows binary without them.
        let script = windows_resource_script(&build);
        embed_resource::compile_for(&script, ["hamster-wheel"], embed_resource::NONE)
            .manifest_required()
            .expect("compile the hamster-wheel Windows resources (Windows SDK required)");
    }
}

/// How this build identifies itself beyond its version number.
///
/// A deployed executable has to be traceable to a tree. The version number
/// alone is not enough: it changes once per milestone, while the artifact
/// changes every commit. `git describe` gives the nearest tag and the short
/// hash, and marks a dirty tree; a source tree without git still builds.
fn build_stamp() -> String {
    Command::new("git")
        .args(["describe", "--always", "--dirty", "--abbrev=12"])
        .output()
        .ok()
        .filter(|output| output.status.success())
        .and_then(|output| String::from_utf8(output.stdout).ok())
        .map(|stamp| stamp.trim().to_owned())
        .filter(|stamp| !stamp.is_empty())
        .unwrap_or_else(|| "unknown".to_owned())
}

/// Writes the resource script the shipped executable is compiled with.
///
/// It is generated rather than checked in because the version numbers come
/// from Cargo and the stamp from git, and a checked-in copy would go stale
/// silently — which is the problem this exists to fix. The icon is referenced
/// by absolute path because the generated script does not live beside it.
fn windows_resource_script(build: &str) -> PathBuf {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("cargo sets the manifest"));
    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("cargo sets OUT_DIR"));
    let icon = manifest.join("icon/icons/hamster-wheel.ico");
    let version = env::var("CARGO_PKG_VERSION").expect("cargo sets the package version");
    let description =
        env::var("CARGO_PKG_DESCRIPTION").unwrap_or_else(|_| "Hamster Wheel".to_owned());
    let (major, minor, patch) = numeric_version(&version);

    // Every value below is quoted into an RC string, so a quote or a
    // backslash in one would end the string or escape the next character.
    let escape = |value: &str| value.replace('\\', "\\\\").replace('"', "\\\"");
    let script = format!(
        r#"// Generated by build.rs. Do not edit; edit build.rs.
1 ICON "{icon}"

1 VERSIONINFO
FILEVERSION {major},{minor},{patch},0
PRODUCTVERSION {major},{minor},{patch},0
FILEFLAGSMASK 0x3fL
FILEFLAGS 0x0L
FILEOS 0x40004L
FILETYPE 0x1L
FILESUBTYPE 0x0L
BEGIN
    BLOCK "StringFileInfo"
    BEGIN
        BLOCK "040904b0"
        BEGIN
            VALUE "FileDescription", "{description}"
            VALUE "FileVersion", "{version}"
            VALUE "InternalName", "hamster-wheel"
            VALUE "OriginalFilename", "hamster-wheel.exe"
            VALUE "ProductName", "Hamster Wheel"
            VALUE "ProductVersion", "{version} ({build})"
        END
    END
    BLOCK "VarFileInfo"
    BEGIN
        VALUE "Translation", 0x409, 1200
    END
END
"#,
        icon = escape(&icon.display().to_string()),
        description = escape(&description),
        version = escape(&version),
        build = escape(build),
    );

    let path = out_dir.join("hamster-wheel.rc");
    fs::write(&path, script).expect("write the generated resource script");
    path
}

/// The three numbers a Windows `FILEVERSION` needs, from a Cargo version.
///
/// A pre-release suffix such as `-dev` is dropped: the resource field is
/// numeric, and the full string is still reported as `FileVersion`.
fn numeric_version(version: &str) -> (u16, u16, u16) {
    let mut parts = version
        .split('-')
        .next()
        .unwrap_or(version)
        .split('.')
        .map(|part| part.parse::<u16>().unwrap_or(0));
    (
        parts.next().unwrap_or(0),
        parts.next().unwrap_or(0),
        parts.next().unwrap_or(0),
    )
}
